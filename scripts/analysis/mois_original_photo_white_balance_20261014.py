#!/usr/bin/env python3
"""Deterministically inspect photographed white/nonwhite parity from archived aggregate receipts.

No missing labels are imputed in the original data. No biological fitness,
phylogenetic equilibrium, new colour classifications or hypothesis-selection
p-values are generated by this source-only reporting script.
"""
from __future__ import annotations
import argparse
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "results/source_receipts/global_classified_white_fraction_and_compensation.json"
LAT = ROOT / "results/source_receipts/photo_white_latitudinal_null.json"
MISSING = ROOT / "results/source_receipts/photo_colour_missingness_mnar.json"
OUT = ROOT / "results/mois_original_photo_white_balance_20261014.json"


def build() -> dict:
    a = json.loads(SRC.read_text(encoding="utf-8"))
    b = json.loads(LAT.read_text(encoding="utf-8"))
    c = json.loads(MISSING.read_text(encoding="utf-8"))
    source, photo, comp = a["source"], a["world_photo_white"], a["ecological_compensation"]
    n = source["unique_original_photos"]
    nclass = source["unique_original_4colour_classifiable_photos"]
    nmiss = source["original_unclassifiable_photos"]
    white = photo["original_white_photo_count"]
    coloured = nclass - white
    assert (n, nclass, nmiss, white, coloured) == (100543, 45953, 54590, 21574, 24379)
    assert nclass + nmiss == n and c["all_original_unique_photo_ids"] == n
    assert b["source_sha256"] == source["original_artifact_zip_sha256"] == c["source_original_archive_sha256"]
    pct = round(100 * white / nclass, 6)
    threshold = (n / 2 - white) / nmiss
    scenarios = [
        {
            "unclassified_white_assumed_fraction": round(p, 8),
            "hypothetical_all_opportunities_white_percent": round(100 * (white + nmiss*p) / n, 6)
        } for p in [0, .25, .5, threshold, .75, 1]
    ]
    latitude = photo["true_photo_site_latitude"]
    assert sum(x["n"] for x in latitude) == b["n_original_classified_geotagged_photos"] == 45879
    assert sum(x["white_n"] for x in latitude) == 21550
    assert math.isclose(
        max(x["fraction"] for x in latitude)*100-min(x["fraction"] for x in latitude)*100,
        b["observed_range_white_percentage_points"], abs_tol=1e-12
    )
    assert comp["tested_negative_compensation_supported"] is False
    assert math.isclose(
        comp["species_compositional_component_variance"]
        + comp["within_species_local_component_variance"]
        + 2 * comp["component_covariance"],
        comp["photo_weighted_cell_whiteness_variance"], abs_tol=1e-12
    )
    return {
        "schema": "mois_original_photo_white_balance_exploration_v1",
        "role": "New deterministic calculations from frozen source aggregate receipts; descriptive and hypothetical only, not evolutionary selection or biological replication",
        "sources": {
            "world": "results/source_receipts/global_classified_white_fraction_and_compensation.json",
            "lat": "results/source_receipts/photo_white_latitudinal_null.json",
            "missing": "results/source_receipts/photo_colour_missingness_mnar.json",
            "original_photo_sha256": source["original_artifact_zip_sha256"]
        },
        "photos": {
            "unique_opportunities": n,
            "classified": nclass,
            "white": white,
            "coloured": coloured,
            "unclassified": nmiss,
            "white_of_classified_percent": pct,
            "coloured_of_classified_percent": round(100*coloured/nclass, 6),
            "white_minus_exact_50_percentage_points": round(pct-50, 6),
            "classified_coloured_to_white_relabels_to_exceed_half": math.ceil(nclass/2-white)
        },
        "hypothetical_all_photo_balance": {
            "all_opportunities_white_percent_bounds": [round(100*white/n, 6),round(100*(white+nmiss)/n, 6)],
            "fraction_white_among_unclassified_needed_for_exact_50_percent": round(threshold, 8),
            "missing_white_assumption_scenarios": scenarios,
            "interpretation": "Unclassified photo opportunities may lack identifiable flower organs; these are hypothetical latent hue assignments, not measured missing phenotypes. A photo-weighted 50:50 cannot establish taxon-weighted, individual or genetically maintained morph frequencies."
        },
        "latitudinal": {
            "classified_geotagged_photo_n": b["n_original_classified_geotagged_photos"],
            "original_absolute_latitude_groups": [
                {"absolute_latitude_deg":x["band"],"photo_n":x["n"],"classified_white_n":x["white_n"],
                 "classified_white_percent":round(100*x["fraction"],6)} for x in latitude
            ],
            "range_pp": round(b["observed_range_white_percentage_points"],6),
            "within_species_photo_label_shuffle_one_sided_p_unusually_even": b["conditional_colour_photo_label_nulls"]["within_species"]["one_sided_p_observed_unusually_even_or_lower_range"],
            "within_genus_photo_label_shuffle_one_sided_p_unusually_even": b["conditional_colour_photo_label_nulls"]["within_genus"]["one_sided_p_observed_unusually_even_or_lower_range"],
            "null_draws": b["conditional_colour_photo_label_nulls"]["within_species"]["null_sample_count"],
            "interpretation": "These preserve observed group photo-white totals and photo opportunities; they test unusual latitudinal evenness conditional on group labels, not biologically regulated 50:50."
        },
        "spatial_components": {
            "n_evaluable_source_cells": comp["evaluable_geographic_cells"],
            "n_repeat_species": comp["repeat_species"],
            "photo_n": comp["photos_in_test"],
            "variance_between_species_composition": comp["species_compositional_component_variance"],
            "variance_within_species_local": comp["within_species_local_component_variance"],
            "covariance_between_and_within": comp["component_covariance"],
            "null_one_sided_p_negative_compensation": comp["negative_compensation_one_sided_p"],
            "original_negative_compensation_supported": comp["tested_negative_compensation_supported"],
            "source_depth_sensitivity_positive_not_bootstrap_stable": a["robustness"]["positive_component_covariance_source_photo_5plus_species_not_bootstrap_stable"],
            "interpretation": "The hypothesized negative species-turnover versus local-phenotype compensation was not supported; these covariance components are photographic geographic decompositions, not fitness or inverse-frequency selection."
        },
        "conclusions": {
            "observed_classified_photos_exactly_half": False,
            "all_photo_white_half_ruled_out": False,
            "biological_species_half_ratio_estimable_from_aggregate": False,
            "evidence_for_frequency_dependent_balancing_selection": False,
            "evidence_for_pigment_cost_or_fitness_crossing": False,
            "observational_hypothesis": "White frequency varies with rainfall across source genus-conditioned species, but frequency-dependent maintenance and pigment benefits/costs are distinct, as-yet-untested mechanisms."
        }
    }


def main() -> None:
    ap = argparse.ArgumentParser()
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = ap.parse_args()
    report = build()
    if args.write:
        OUT.write_text(json.dumps(report, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        print("Wrote", OUT)
    else:
        assert json.loads(OUT.read_text(encoding="utf-8")) == report
        print("PASS photo-white fraction, parity missingness tipping, latitudinal nulls, no compensation")


if __name__ == "__main__":
    main()
