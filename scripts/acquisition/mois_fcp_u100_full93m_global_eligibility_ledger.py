#!/usr/bin/env python3
"""Aggregate all16 independently frozen original 93m FCP-U100 source groups.

NO image acquisition or colour inference. The 93,209,351 original PHOTO-ID
source population is already disjoint across 128 taxon-modulo source parts
and all 14 observation-hash tiers. Each of the 16 upstream group jobs reads
only its 8 assigned parts and stores SHA-verified original photos, observation
counts and up to 100 selected independent-photo observations per taxon.
This script joins ONLY group receipts and 42,111 taxon source-availability
rows; never downloads another 4GB of 93m source archives, photo URLs or the
2m-or-fewer selected photo-ID future-ROI table.

FCP original 447,500 ROIs are ALREADY measured and previously reused in MOIS.
Any future selected U100 original-photo ROIs MUST first deduplicate their
photo IDs/observations against the FCP and MOIS pixel registry and continue
to report the original per-taxon N and per-observation M probabilities.
"""
from __future__ import annotations

import argparse
from collections import Counter
import csv
import json
import os
from pathlib import Path
import shutil
import tempfile

from scripts.acquisition.mois_onepass_full93m_target_tiers import (
    EXPECTED_PHOTOS, EXPECTED_TAXA, sha256, require,
)
from scripts.acquisition.mois_fcp_u100_full93m_source_onepass_group import (
    SCHEMA as GROUP_SCHEMA, FCP_TARGET, N_GROUPS, TIERS,
)

SCHEMA = "mois_all_42111_taxa_FCP_U100_full_93209351_source_eligibility_v1"
HEADER = (
    "inat_taxon_id","species","full_93m_original_observation_count",
    "full_93m_original_photo_count","FCP_U100_source_eligible",
    "FCP_U100_missing_observations","selected_observed_months",
    "selected_latitude_bands"
)


def aggregate(group_dirs, output, *,
              expected_groups=N_GROUPS,
              expected_taxa=EXPECTED_TAXA,
              expected_photos=EXPECTED_PHOTOS):
    output=Path(output)
    require(not output.exists(), "Refuse to change immutable FCP source census")
    require(len(group_dirs)==expected_groups and 1<=expected_groups<=N_GROUPS,
            "A signed original FCP U100 source taxonomic group is absent")
    observed_groups=set()
    taxa=set()
    all_receipts=[]
    availability=[]
    raw_photos=raw_obs=eligible=photo_target=supported=unknown=0
    seen_group_registry_shas=set()
    for directory in group_dirs:
        directory=Path(directory)
        receipt=directory/"fcp_U100_full93m_group_source_receipt.json"
        roster=directory/"fcp_original100_complete_nominal_taxa_source_eligibility.csv"
        r=json.loads(receipt.read_text(encoding="utf-8"))
        group=r.get("original_taxon_modulo_source_group")
        require(type(group) is int and 0<=group<expected_groups
                and group not in observed_groups
                and r.get("schema")==GROUP_SCHEMA
                and r.get("full_original_photo_source_IDs")==expected_photos
                and r.get("full_original_named_plant_taxa")==expected_taxa
                and r.get("source_tier_archives_read_exactly_once")==TIERS
                and r.get("no_original_image_downloads") is True
                and r.get("no_original_ROI_or_hue_inferences") is True
                and r.get("original_source_eligibility_and_all_taxa_preserved") is True
                and r.get("FCP_original_photo_observation_target_per_taxon")==FCP_TARGET
                and r.get("all_old_FCP_MOIS_original_photo_IDs_must_be_reused_before_any_new_ROI") is True
                and r.get("FCP_original_iNaturalist_H9_phenology_annotation_verified_for_all_new_MOIS_photos") is False
                and r.get("full_WCVP_taxonomy_and_native_wild_flowering_photo_status_verified") is False,
                "One signed original photo group not generated by the frozen FCP source design")
        signature=r["source_group_original_photo_ID_SHA"]
        require(type(signature) is dict
                and signature.get("group")==group
                and signature.get("original_photos")==r["source_original_photo_IDs"]
                and len(signature.get("original_tier_counts",{}))==TIERS
                and sum(signature["original_tier_counts"].values())==
                    r["source_original_photo_IDs"]
                and signature.get("original_group_receipt_SHA256"),
                "Original full 14-tier photo source SHA group audit missing")
        group_registry=signature.get("original_full_93m_source_registry_SHA256")
        require(group_registry and group_registry==r["source_group_original_photo_ID_SHA"][
            "original_full_93m_source_registry_SHA256"], "Incorrect source registry in group")
        seen_group_registry_shas.add(group_registry)
        require(sha256(roster)==r["taxon_source_eligibility_SHA256"]
                and r["U100_complete_original_photo_candidate_SHA256"]
                and r["unsupported_original_photo_unknown_SHA256"]
                and len(r["precolour_ROI_worker_shard_SHA256"])>=0,
                "Original taxon availability/photo-ID source outputs unsigned")

        seen_count=seen_photos=seen_obs=seen_eligible=0
        local_taxa=set()
        with roster.open(newline="",encoding="utf-8") as f:
            rd=csv.DictReader(f)
            require(tuple(rd.fieldnames or ())==HEADER,
                    "Source taxon eligibility column order changed")
            for row in rd:
                taxon=row["inat_taxon_id"]
                require(taxon.isdecimal() and bool(row["species"])
                        and int(taxon)%128//8==group
                        and taxon not in local_taxa and taxon not in taxa,
                        "Duplicated/wrong-modulo original photo source taxon")
                local_taxa.add(taxon);taxa.add(taxon)
                n=int(row["full_93m_original_observation_count"])
                m=int(row["full_93m_original_photo_count"])
                eligible_status=str(n>=FCP_TARGET).lower()
                require(n>=0 and m>=n
                        and row["FCP_U100_source_eligible"]==eligible_status
                        and int(row["FCP_U100_missing_observations"])==max(0,FCP_TARGET-n),
                        "Taxon 100-photo original observation availability was altered")
                seen_count+=1;seen_obs+=n;seen_photos+=m;seen_eligible+=n>=FCP_TARGET
                availability.append(row)
        require(seen_count==r["source_nominal_taxa"]
                and seen_obs==r["source_distinct_observations"]
                and seen_photos==r["source_original_photo_IDs"]
                and seen_eligible==r["FCP_U100_source_eligible_nominal_taxa"]
                and r["FCP_U100_source_original_photo_opportunities"]==FCP_TARGET*seen_eligible
                and r["FCP_U100_original_photo_ROI_targets_loader_supported"]+
                    r["FCP_U100_photo_unsupported_format_technical_unknown"]==
                    FCP_TARGET*seen_eligible,
                "Original FCP U100 group selected source/photos/eligibility count mismatch")
        observed_groups.add(group)
        raw_photos+=seen_photos
        raw_obs+=seen_obs
        eligible+=seen_eligible
        photo_target+=FCP_TARGET*seen_eligible
        supported+=r["FCP_U100_original_photo_ROI_targets_loader_supported"]
        unknown+=r["FCP_U100_photo_unsupported_format_technical_unknown"]
        all_receipts.append({
            "group":group,"original_photos":seen_photos,
            "distinct_observations":seen_obs,"nominal_taxa":seen_count,
            "eligible_taxa":seen_eligible,"FCP_U100_source_photos":FCP_TARGET*seen_eligible,
            "group_receipt_sha256":sha256(receipt),
            "source_roster_sha256":sha256(roster),
            "original_14tier_group_archive_receipt_sha256":
                signature["original_group_receipt_SHA256"],
        })
    require(seen_group_registry_shas and len(seen_group_registry_shas)==1,
            "Sixteen source groups have mismatched 93m original-photo registers")
    if expected_groups==N_GROUPS:
        require(observed_groups==set(range(N_GROUPS))
                and len(taxa)==expected_taxa
                and raw_photos==expected_photos,
                "The complete global 93m source photo IDs / 42111 taxa were not conserved")
    require(photo_target==FCP_TARGET*eligible and
            photo_target==supported+unknown and 0<=raw_obs<=raw_photos,
            "FCP U100 original photo opportunity summary malformed")
    availability.sort(key=lambda row:int(row["inat_taxon_id"]))
    out=output.parent
    out.mkdir(parents=True,exist_ok=True)
    staged=Path(tempfile.mkdtemp(prefix="mois-fcp-full-global-",dir=out))
    try:
        roster=staged/"full42111_nominal_taxa_original_U100_source_eligibility.csv"
        with roster.open("w",encoding="utf-8",newline="") as f:
            w=csv.DictWriter(f,fieldnames=HEADER,lineterminator="\n")
            w.writeheader();w.writerows(availability)
        metric={
            "schema":SCHEMA,
            "source_all_original_photo_metadata_IDs":expected_photos,
            "all_source_nominal_taxon_IDs":expected_taxa,
            "source_FCP_style_exact100_photo_observation_taxa":eligible,
            "source_FCP_style_exact100_observation_photo_targets":photo_target,
            "source_FCP_style_supported_original_photo_extension_targets":supported,
            "source_FCP_style_unsupported_photo_unknowns":unknown,
            "source_taxa_with_less_than100_different_original_observations":
                sum(0<int(row["full_93m_original_observation_count"])<FCP_TARGET
                    for row in availability),
            "source_taxa_without_original_observations":
                sum(int(row["full_93m_original_observation_count"])==0
                    for row in availability),
            "all_14tier_original_source_photo_IDs_SHA_verified":True,
            "all_16_source_taxon_groups_independent":expected_groups==N_GROUPS,
            "source_original_distinct_observations":raw_obs,
            "source_original_photo_IDs_reconciled":raw_photos,
            "ratio_source_photo_opportunities_to_exact100_targets":
                expected_photos/photo_target if photo_target else None,
            "expected_max_unique_ROI_work_100_per_eligible_taxon_including_old_image_reuse":photo_target,
            "complete_42111_taxa_eligibility_csv_sha256":sha256(roster),
            "full93m_original_source_registry_sha256":next(iter(seen_group_registry_shas)),
            "group_original_photo_SHA_proof":sorted(all_receipts,key=lambda x:x["group"]),
            "photo_ROI_pixels_opened_or_reinferred":0,
            "signed_old_original_FCP447500_photo_outcomes_must_be_reused_first":True,
            "botanical_H9_flowering_annotated_for_entire_photo_universe":False,
            "native_wild_flower_photo_status_verified":False,
            "source_100taxon_scheme_is_not_worldwide_unbiased_flora_colour_rate":True,
        }
        (staged/"fcp_U100_all42111_nominal_taxa_full93m_source_receipt.json").write_text(
            json.dumps(metric,indent=2,sort_keys=True)+"\n")
        os.replace(staged,output)
        print("MOIS_FCP_ALL93M_EXACT100_ALL42111_TAXA_SOURCE_DONE",
              json.dumps({k:metric[k] for k in (
                  "source_all_original_photo_metadata_IDs",
                  "all_source_nominal_taxon_IDs",
                  "source_FCP_style_exact100_photo_observation_taxa",
                  "source_FCP_style_exact100_observation_photo_targets",
                  "source_original_distinct_observations",
                  "ratio_source_photo_opportunities_to_exact100_targets")},sort_keys=True),flush=True)
        return metric
    except BaseException:
        shutil.rmtree(staged,ignore_errors=True)
        raise


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("--group-dir",type=Path,nargs="+",required=True)
    p.add_argument("--output",type=Path,required=True)
    a=p.parse_args()
    aggregate(a.group_dir,a.output)


if __name__=="__main__":
    main()
